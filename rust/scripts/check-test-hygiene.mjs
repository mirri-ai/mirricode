#!/usr/bin/env node
// Test-hygiene gate for the rust workspace (plans/16 Task 3, design §4.5 #7).
//
// Enforces the test iron rules (rust/AGENTS.md 测试铁律) mechanically:
//   (a) every top-level `tests/*.rs` integration-test binary must carry a
//       `// layer: T<n>` header tag within its first 20 lines;
//   (b) test code (whole `tests/` files + `#[cfg(test)]` module bodies in
//       `src/`) must not call bare `std::env::set_var` / `remove_var`;
//   (c) test code must not call bare `thread::sleep`.
//   (d) test code must not spawn a real subprocess (`std::process::Command` /
//       `tokio::process::Command` / `Command::new`) or declare a `real-*`
//       semantic window (`// hygiene-allow: real-…`) unless the enclosing
//       test fn carries `#[ignore]` (R-layer attribution, design §3); a spawn
//       may instead carry a line-level `// hygiene-allow: <reason>`. Known
//       limits: wrapper-mediated spawns (mirri_os::new_command & friends) are
//       invisible here, and helper fns cannot carry `#[ignore]` — their
//       caller tests are the attribution target.
//
// "Bare" = the call line is not covered by a guard context and carries no
// `// hygiene-allow:` exemption. Guard context for env mutation: one of the
// marker strings `env_lock` / `ENV_LOCK` / `home_lock` / `acquire_env_lock` /
// `EnvGuard` / `mirri_test_support` / `test_support` appearing on the same
// line or within the 10 preceding lines (deliberately coarse — precision is
// bought later by R2/R4 migration, the gate's job today is ratchet-only).
// For sleep, `wait_for` on the same line counts as guard context too.
//
// Baseline + zero-tolerance: `rust/scripts/test-hygiene-baseline.json`
// whitelists existing violations (key `"<relpath>:<line>"`, value
// `{type, reason}`).
//   - a violation NOT in the baseline → exit 1 (new debt is rejected);
//   - a baseline entry that no longer matches → "stale, removable" warning
//     only (baseline shrinks as migrations land, never grows);
//   - ZERO-TOLERANCE for sleep, allow-listed coverage (batch 6a/6b): a
//     sleep baseline entry only covers its violation when its reason
//     matches `/^(poll-step|negative-wait|real-|D:)/`. Everything else —
//     a missing reason, `legacy: …`, the `Legacy:` case variant, ad-hoc
//     prose — is NOT coverage: the violation is reported fresh (exit 1).
//     Legacy sleep debt cannot be (re)entrenched in the baseline; the
//     sanctioned reasons stay exempt. Effect: any new bare sleep or
//     legacy revival fails the gate directly.
//   - `--write-baseline` growth guard (batch 6b): re-anchoring that adds
//     entries whose file+type group has no corresponding old entry (a new
//     group, or a group whose entry count grew) warns on stderr and lists
//     them in the exit message — visible, but does not block the write
//     (re-anchoring is an operator action).
// Line numbers drift when files are edited, so stale detection matches by
// file + type + line; a drifted line simply re-baselines at the new position
// when the entry was legitimately migrated/regenerated by Task 7+.
//
// Usage:
//   node rust/scripts/check-test-hygiene.mjs            # gate: exit 1 on new violation
//   node rust/scripts/check-test-hygiene.mjs --report   # counts only, always exit 0
//   node rust/scripts/check-test-hygiene.mjs --write-baseline  # regenerate baseline
//                                                          # (first run / Task 7 only)
//   node rust/scripts/check-test-hygiene.mjs --root <dir>  # scan an alternate rust
//                                                          # root (tests only)

import { readdirSync, readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { join, relative, dirname, basename, resolve } from 'node:path';

const rustDir = join(import.meta.dirname, '..');
const rootArgIdx = process.argv.indexOf('--root');
if (rootArgIdx >= 0 && (rootArgIdx + 1 >= process.argv.length || process.argv[rootArgIdx + 1].startsWith('-'))) {
  console.error('test-hygiene: --root requires a directory argument');
  process.exit(2);
}
const rootDir = rootArgIdx >= 0 ? resolve(process.argv[rootArgIdx + 1]) : rustDir;
const cratesDir = join(rootDir, 'crates');
const baselinePath = join(rootDir, 'scripts', 'test-hygiene-baseline.json');
const reportMode = process.argv.includes('--report');
const writeBaselineMode = process.argv.includes('--write-baseline');

// --- shared lexical machinery (same state machine as check-zero-io.mjs) ----

/**
 * Replace the *content* of comments and string literals with equal-length
 * whitespace (newlines preserved), so scanning ignores prose that merely
 * *discusses* the banned calls while line numbers stay aligned with the
 * original file. Mirrors the masker in check-zero-io.mjs (line / nested
 * block comment / string / raw string / char-vs-lifetime).
 */
function maskCommentsAndStrings(text) {
  const out = text.split('');
  const isIdent = (c) => /[\w$]/.test(c ?? ' ');
  const blank = (i) => {
    if (out[i] !== '\n') out[i] = ' ';
  };
  let i = 0;
  const n = text.length;
  while (i < n) {
    const c = text[i];
    if (c === '/' && text[i + 1] === '/') {
      while (i < n && text[i] !== '\n') {
        blank(i);
        i++;
      }
    } else if (c === '/' && text[i + 1] === '*') {
      let depth = 0;
      while (i < n) {
        if (text[i] === '/' && text[i + 1] === '*') {
          blank(i);
          blank(i + 1);
          i += 2;
          depth++;
        } else if (text[i] === '*' && text[i + 1] === '/') {
          blank(i);
          blank(i + 1);
          i += 2;
          depth--;
          if (depth === 0) break;
        } else {
          blank(i);
          i++;
        }
      }
    } else if (c === '"') {
      blank(i);
      i++;
      while (i < n && text[i] !== '"') {
        const step = text[i] === '\\' ? 2 : 1;
        for (let k = 0; k < step && i + k < n; k++) blank(i + k);
        i += step;
      }
      if (i < n) {
        blank(i);
        i++;
      }
    } else if (
      c === 'r' &&
      (!isIdent(text[i - 1]) ||
        (text[i - 1] === 'b' && !isIdent(text[i - 2]))) &&
      /["#]/.test(text[i + 1] ?? '')
    ) {
      let hashes = 0;
      let j = i + 1;
      while (text[j] === '#') {
        hashes++;
        j++;
      }
      if (text[j] === '"') {
        const closing = '"' + '#'.repeat(hashes);
        let end = j + 1;
        while (end < n && text.slice(end, end + closing.length) !== closing) end++;
        end = Math.min(end + closing.length, n);
        for (let k = i; k < end; k++) blank(k);
        i = end;
      } else {
        i++;
      }
    } else if (c === "'") {
      const rest = text.slice(i, i + 16);
      const m = rest.match(/^'(\\u\{[0-9a-fA-F_]{1,6}\}|\\.|[^\\'])'/);
      if (m) {
        for (let k = 0; k < m[0].length; k++) blank(i + k);
        i += m[0].length;
      } else {
        i++;
      }
    } else {
      i++;
    }
  }
  return out.join('');
}

/**
 * Find the end of a `{ ... }` body that opens at `openBrace`, skipping braces
 * inside strings / char literals / comments. Returns the index just past the
 * matching `}`.
 */
function findBodyEnd(text, openBrace) {
  let i = openBrace + 1;
  while (i < text.length) {
    const c = text[i];
    if (c === '/' && text[i + 1] === '/') {
      while (i < text.length && text[i] !== '\n') i++;
    } else if (c === '/' && text[i + 1] === '*') {
      i += 2;
      while (i < text.length && !(text[i] === '*' && text[i + 1] === '/')) i++;
      i += 2;
    } else if (c === '"') {
      i++;
      while (i < text.length && text[i] !== '"') i += text[i] === '\\' ? 2 : 1;
      i++;
    } else if (c === 'r' && !/[\w$]/.test(text[i - 1] ?? ' ') && /["#]/.test(text[i + 1] ?? '')) {
      let hashes = 0;
      let j = i + 1;
      while (text[j] === '#') {
        hashes++;
        j++;
      }
      if (text[j] === '"') {
        i = j + 1;
        const closing = '"' + '#'.repeat(hashes);
        while (i < text.length && text.slice(i, i + closing.length) !== closing) i++;
        i += closing.length;
      } else {
        i++;
      }
    } else if (c === "'") {
      const rest = text.slice(i, i + 16);
      const m = rest.match(/^'(\\u\{[0-9a-fA-F_]{1,6}\}|\\.|[^\\'])'/);
      if (m) {
        i += m[0].length;
      } else {
        i++;
      }
    } else if (c === '{') {
      i = findBodyEnd(text, i);
    } else if (c === '}') {
      return i + 1;
    } else {
      i++;
    }
  }
  return text.length;
}

// --- test-code extraction ---------------------------------------------------

/**
 * From a `src/` file, return the concatenated text of all *inline*
 * `#[cfg(test)] mod … { … }` bodies (and `#[cfg(all(test, …))]` / bare
 * `#[cfg(test)]` fn/impl targets — the strip-vs-extract logic differs from
 * check-zero-io only in which side we keep). Line numbers are preserved
 * relative to the original file by padding with newlines. External test
 * module declarations (`#[cfg(test)] mod name;`) yield their file paths for
 * separate inclusion.
 */
function extractTestSegments(rawText) {
  const externalMods = [];
  const segments = [];
  const masked = maskCommentsAndStrings(rawText);
  const cfgTestRe =
    /#\[[^\n]*\b(?:cfg\(\s*(?:all\(\s*)?test|cfg_attr\([^)]*,\s*test)\b[^\n]*\]\s*\n?\s*(mod\s+(\w+))?/g;
  let match;
  while ((match = cfgTestRe.exec(masked)) !== null) {
    const afterAttr = masked.slice(match.index + match[0].length);
    if (match[2] !== undefined) {
      // `#[cfg(test)] mod name …`
      if (/^\s*;/.test(afterAttr)) {
        externalMods.push(match[2]);
      } else if (/^\s*\{/.test(afterAttr)) {
        const openBrace =
          match.index + match[0].length + afterAttr.match(/^\s*\{/)[0].length - 1;
        const end = findBodyEnd(masked, openBrace);
        // The segment text is padded with leading newlines so that its line
        // numbers already align with the original file — scanRegion must be
        // called with offset 1 (same as whole-file scanning).
        segments.push({
          text: '\n'.repeat((rawText.slice(0, match.index).match(/\n/g) ?? []).length) +
            rawText.slice(match.index, end),
        });
      }
    } else {
      // `#[cfg(test)]` on a bare fn / impl / struct — capture to end of the
      // item (next `}` at brace-depth 1, or the attribute's line if no
      // brace follows). Scan forward for the first `{` within the item head.
      const head = afterAttr;
      const braceOffset = head.search(/\{/);
      if (braceOffset >= 0) {
        const openBrace = match.index + match[0].length + braceOffset;
        const end = findBodyEnd(masked, openBrace);
        segments.push({
          text: '\n'.repeat((rawText.slice(0, match.index).match(/\n/g) ?? []).length) +
            rawText.slice(match.index, end),
        });
      }
    }
  }
  return { segments, externalMods };
}

// --- per-rule checks ---------------------------------------------------------

const LAYER_TAG_RE = /\/\/\s*layer:\s*T[0-3]\b/;
const HYGIENE_ALLOW_RE = /\/\/\s*hygiene-allow:\s*\S/;

const ENV_CALL_PATTERNS = [
  { name: 'set_var', re: /\bstd::env::set_var\b/ },
  { name: 'remove_var', re: /\bstd::env::remove_var\b/ },
];
// Both wait shapes are banned by the isolation contract §4.2 #4: the
// "固定 tokio::time::sleep" clause is explicit, and the legacy sleep debt
// (344+ hits) is dominated by `tokio::time::sleep` in the embedded tests.
const SLEEP_PATTERNS = [
  { name: 'sleep', re: /\bthread::sleep\b/ },
  { name: 'sleep', re: /\btokio::time::sleep\b/ },
];

// Guard-marker strings for env mutation (deliberately coarse, see header).
const ENV_GUARD_MARKERS = [
  'env_lock',
  'ENV_LOCK',
  'home_lock',
  'acquire_env_lock',
  'EnvGuard',
  'mirri_test_support',
  'test_support',
];
// Guard markers for sleep: the sanctioned polling helper family.
const SLEEP_GUARD_MARKERS = ['wait_for'];

// --- rule R: real-env attribution --------------------------------------------
// Coarse ratchet, same philosophy as the guard markers: raw real-subprocess
// spawns and `real-*` semantic windows in test code must be attributed to
// the real-environment tier — an `#[ignore]`d test fn (R-layer, design §3)
// or, for spawns only, a line-level `// hygiene-allow: <reason>`. Known
// limits (documented, adjudicated by the per-site audit, not this gate):
// wrapper-mediated spawns (mirri_os::new_command & friends) are invisible
// here, and helper fns cannot carry #[ignore] — their CALLER tests are the
// attribution target.
const REAL_ENV_PATTERNS = [
  { name: 'real-env', re: /\bstd::process::Command\b/ },
  { name: 'real-env', re: /\btokio::process::Command\b/ },
  { name: 'real-env', re: /\bCommand::new\b/ },
];
const REAL_HYGIENE_ALLOW_RE = /\/\/\s*hygiene-allow:\s*real-/;
const IGNORE_ATTR_RE = /#\[\s*ignore\b/;
const TEST_ATTR_RE = /#\[\s*(?:tokio::)?test\b/;

function hasGuardContext(rawLines, lineIdx, markers) {
  const windowStart = Math.max(0, lineIdx - 15);
  for (let i = windowStart; i <= lineIdx; i++) {
    const raw = rawLines[i] ?? '';
    // Guard markers are identifiers / comment prose — scan the raw line
    // (the masked line would blank them out along with all other comments).
    for (const marker of markers) {
      if (raw.includes(marker)) return true;
    }
  }
  return false;
}

/**
 * Spans of `fn NAME … { … }` bodies in masked text, each with its attribute
 * region (text from the previous fn's body end up to the `fn` keyword, so
 * doc comments and #[...] attrs belong to the following fn). Nested fns
 * fold into the outer span (fnRe.lastIndex skips past the body); trait
 * method signatures without bodies (`fn f();`) are skipped.
 */
function collectFnSpans(masked) {
  const spans = [];
  const fnRe = /\bfn\s+\w+/g;
  let m;
  while ((m = fnRe.exec(masked)) !== null) {
    const after = masked.slice(m.index);
    const semi = after.indexOf(';');
    const braceOffset = after.search(/\{/);
    if (braceOffset < 0 || (semi >= 0 && semi < braceOffset)) continue;
    const bodyStart = m.index + braceOffset;
    const bodyEnd = findBodyEnd(masked, bodyStart);
    spans.push({
      attrStart: spans.at(-1)?.bodyEnd ?? 0,
      attrEnd: m.index,
      bodyStart,
      bodyEnd,
    });
    fnRe.lastIndex = bodyEnd;
  }
  return spans;
}

/**
 * Attribution for a hit at char `offset`: is it inside a test fn
 * (`#[test]` / `#[tokio::test]` in the fn's attribute region) and does that
 * fn carry `#[ignore]` (plain or `#[ignore = "reason"]`)? The attribute
 * region is read from the *masked* text, so doc-comment prose that merely
 * mentions `#[ignore]` cannot exempt a spawn. Hits outside any fn body
 * report { isTest: false, hasIgnore: false }.
 */
function fnAttribution(masked, offset, spans) {
  for (const s of spans) {
    if (offset >= s.bodyStart && offset < s.bodyEnd) {
      const attrs = masked.slice(s.attrStart, s.attrEnd);
      return {
        isTest: TEST_ATTR_RE.test(attrs),
        hasIgnore: IGNORE_ATTR_RE.test(attrs),
      };
    }
  }
  return { isTest: false, hasIgnore: false };
}

/**
 * Scan one test-code region (either a whole `tests/` file or an extracted
 * `#[cfg(test)]` segment) for violations. `offsetLines` maps region line 1
 * to the file's real line number.
 */
function scanRegion(text, offsetLines, path) {
  const violations = [];
  const rawLines = text.split('\n');
  const maskedText = maskCommentsAndStrings(text);
  const maskedLines = maskedText.split('\n');
  const fnSpans = collectFnSpans(maskedText);
  const lineOffsets = [];
  let acc = 0;
  for (const line of rawLines) {
    lineOffsets.push(acc);
    acc += line.length + 1;
  }
  for (let i = 0; i < rawLines.length; i++) {
    // Per-line dedupe: multiple patterns on the same line report once
    // (baseline key is file:line, one entry per line).
    let seenSleep = false;
    let seenRealEnv = false;
    const fileLine = offsetLines + i;
    const raw = rawLines[i] ?? '';
    const maskedLine = maskedLines[i] ?? '';
    const attr = () => fnAttribution(maskedText, lineOffsets[i], fnSpans);
    // Rule R(b): a `real-*` semantic window must sit in an #[ignore]d TEST
    // fn. Helpers are exempt (their caller tests are the attribution
    // target); the reason prefix itself is the signal, so hygiene-allow
    // cannot double as an escape here.
    if (REAL_HYGIENE_ALLOW_RE.test(raw)) {
      const a = attr();
      if (a.isTest && !a.hasIgnore && !seenRealEnv) {
        seenRealEnv = true;
        violations.push({
          file: path,
          line: fileLine,
          type: 'real-env',
          kind: 'real-time window without #[ignore]',
          text: raw.trim(),
        });
      }
    }
    if (HYGIENE_ALLOW_RE.test(raw)) continue;
    for (const { name, re } of ENV_CALL_PATTERNS) {
      if (re.test(maskedLine)) {
        if (!hasGuardContext(rawLines, i, ENV_GUARD_MARKERS)) {
          violations.push({
            file: path,
            line: fileLine,
            type: name === 'set_var' ? 'set_var' : 'set_var',
            kind: name,
            text: raw.trim(),
          });
        }
      }
    }
    for (const { re } of SLEEP_PATTERNS) {
      if (re.test(maskedLine) && !seenSleep) {
        seenSleep = true;
        if (!hasGuardContext(rawLines, i, SLEEP_GUARD_MARKERS)) {
          violations.push({
            file: path,
            line: fileLine,
            type: 'sleep',
            kind: 'fixed sleep',
            text: raw.trim(),
          });
        }
      }
    }
    // Rule R(a): a raw real-subprocess spawn must be attributed to the
    // real-environment tier — the enclosing TEST fn carries #[ignore] (helpers
    // cannot legally carry it, so their caller tests are the attribution
    // target and their spawns stay visible) — or the line carries a
    // line-level hygiene-allow, which the `continue` above already granted
    // (reaching here means no hygiene-allow on this line).
    for (const { re } of REAL_ENV_PATTERNS) {
      if (!re.test(maskedLine)) continue;
      if (!seenRealEnv) {
        seenRealEnv = true;
        const a = attr();
        // An inert #[ignore] on a non-test fn is not attribution: it has no
        // effect at compile time and only hides a site the audit must see.
        if (!(a.isTest && a.hasIgnore)) {
          violations.push({
            file: path,
            line: fileLine,
            type: 'real-env',
            kind: 'real subprocess spawn without #[ignore]',
            text: raw.trim(),
          });
        }
      }
      break;
    }
  }
  return violations;
}

/** Check `// layer:` tag in a tests/*.rs binary file's first 20 lines. */
function checkLayerTag(rawText, path) {
  const head = rawText.split('\n').slice(0, 20).join('\n');
  if (!LAYER_TAG_RE.test(head)) {
    return [{ file: path, line: 1, type: 'layer', kind: 'missing layer tag', text: '(file header, first 20 lines)' }];
  }
  return [];
}

// --- scan --------------------------------------------------------------------

function listRustFiles(dir) {
  const out = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) {
      out.push(...listRustFiles(path));
    } else if (entry.isFile() && entry.name.endsWith('.rs')) {
      out.push(path);
    }
  }
  return out;
}

/**
 * Test-target names declared under `[[test]]` in a crate's Cargo.toml
 * (default target = file stem). Files under `tests/` that are NOT test
 * targets are helper code (`tests/common/mod.rs`, `tests/bin/*.rs` fixtures
 * declared as `[[bin]]`) — scanned as test code but exempt from the layer
 * tag (they are not test binaries).
 */
function declaredTestTargets(crateDir) {
  const tomlPath = join(crateDir, 'Cargo.toml');
  const targets = new Set();
  if (!existsSync(tomlPath)) return targets;
  const toml = readFileSync(tomlPath, 'utf8');
  let section = null;
  for (const line of toml.split('\n')) {
    const sec = line.match(/^\s*\[\[([^\]]+)\]\]/);
    if (sec) {
      section = sec[1].trim();
      continue;
    }
    if (section === 'test') {
      const name = line.match(/^\s*name\s*=\s*"([^"]+)"/);
      if (name) targets.add(name);
      const path = line.match(/^\s*path\s*=\s*"([^"]+)"/);
      if (path) targets.add(basename(path[1], '.rs'));
    }
  }
  return targets;
}

const violations = [];
let scannedTestBinaries = 0;
let scannedTestHelperFiles = 0;
let scannedSrcTestSegments = 0;
let guardedEnvCalls = 0;
let guardedSleeps = 0;

/**
 * Follow a `mod NAME;` declaration in a file to its source file, following
 * rustc's module resolution: children of `foo.rs` live in `foo/NAME.rs` or
 * `foo/NAME/mod.rs`; children of `mod.rs` / `lib.rs` / `main.rs` live beside
 * the declaring file. This is what makes `embedded_server/tests.rs` resolve
 * its `mod b2_notification_tests;` to `embedded_server/tests/b2_*.rs`.
 */
function modFileFor(declaringFile, name) {
  const dir = dirname(declaringFile);
  const base = basename(declaringFile);
  const stem = base.replace(/\.rs$/, '');
  const candidates =
    base === 'mod.rs' || base === 'lib.rs' || base === 'main.rs'
      ? [join(dir, `${name}.rs`), join(dir, name, 'mod.rs')]
      : [join(dir, stem, `${name}.rs`), join(dir, stem, name, 'mod.rs')];
  for (const c of candidates) {
    if (existsSync(c)) return c;
  }
  return null;
}

/**
 * Scan one whole file that is entirely test code (a `tests/` file, an
 * external `#[cfg(test)] mod NAME;` file, or a nested mod file reached from
 * one). `requireLayerTag` only for actual test-binary entry points.
 * Deduped by path: a file reachable through several mod trees (e.g.
 * `tests/common/mod.rs` from every binary that declares it) is scanned once.
 */
const scannedWholeFiles = new Set();

function scanWholeTestFile(file, rel, requireLayerTag) {
  if (scannedWholeFiles.has(file)) return;
  scannedWholeFiles.add(file);
  const raw = readFileSync(file, 'utf8');
  if (requireLayerTag) {
    violations.push(...checkLayerTag(raw, rel));
  }
  violations.push(...scanRegion(raw, 1, rel));
  countGuarded(raw);
  // Recurse into plain `mod NAME;` children — under test cfg the whole
  // subtree is test code (e.g. embedded_server/tests.rs → b2_* files).
  for (const name of listPlainModDeclarations(raw)) {
    const child = modFileFor(file, name);
    if (child) scanWholeTestFile(child, relative(rootDir, child), false);
  }
}

function countGuarded(raw) {
  const masked = maskCommentsAndStrings(raw).split('\n');
  const rawLines = raw.split('\n');
  for (let i = 0; i < rawLines.length; i++) {
    if (HYGIENE_ALLOW_RE.test(rawLines[i] ?? '')) continue;
    if (ENV_CALL_PATTERNS.some(({ re }) => re.test(masked[i] ?? ''))) {
      if (hasGuardContext(rawLines, i, ENV_GUARD_MARKERS)) guardedEnvCalls++;
    }
    if (SLEEP_PATTERNS.some(({ re }) => re.test(masked[i] ?? ''))) {
      if (hasGuardContext(rawLines, i, SLEEP_GUARD_MARKERS)) guardedSleeps++;
    }
  }
}

/** All `mod NAME;` (declaration form) names in a file, comment-masked. */
function listPlainModDeclarations(rawText) {
  const masked = maskCommentsAndStrings(rawText);
  const names = [];
  const modRe = /^\s*(?:pub(?:\s*\([^)]*\))?\s+)?mod\s+(\w+)\s*;/gm;
  let m;
  while ((m = modRe.exec(masked)) !== null) names.push(m[1]);
  return names;
}

for (const crate of readdirSync(cratesDir, { withFileTypes: true })) {
  if (!crate.isDirectory()) continue;
  const crateDir = join(cratesDir, crate.name);
  // tests/ — top-level .rs files are test binaries (layer tag required);
  // nested .rs files are helper/mod-tree code (scanned, no layer tag). The
  // `[[bin]]`-declared fixture under tests/bin/ is helper code, not a test
  // target (mirri-acp/tests/bin/echo_mcp.rs).
  const testsDir = join(crateDir, 'tests');
  if (existsSync(testsDir)) {
    const declared = declaredTestTargets(crateDir);
    for (const entry of readdirSync(testsDir, { withFileTypes: true })) {
      if (!entry.isFile() || !entry.name.endsWith('.rs')) continue;
      const file = join(testsDir, entry.name);
      const rel = relative(rootDir, file);
      const isBinary = declared.size === 0 || declared.has(basename(entry.name, '.rs'));
      if (isBinary) {
        scannedTestBinaries++;
        scanWholeTestFile(file, rel, true);
      } else {
        scannedTestHelperFiles++;
        scanWholeTestFile(file, rel, false);
      }
    }
    // Nested helper files (tests/common/, tests/bin/, deeper mod trees)
    // reached via the binary's mod declarations are picked up by
    // scanWholeTestFile's recursion; any remaining nested .rs file not
    // reachable that way is still helper code — scan it without the tag.
    const topRust = new Set(
      readdirSync(testsDir, { withFileTypes: true })
        .filter((e) => e.isFile() && e.name.endsWith('.rs'))
        .map((e) => join(testsDir, e.name)),
    );
    for (const file of listRustFiles(testsDir)) {
      if (topRust.has(file)) continue;
      const rel = relative(rootDir, file);
      scannedTestHelperFiles++;
      scanWholeTestFile(file, rel, false);
    }
  }
  // src/ — inline #[cfg(test)] mod blocks + `#[cfg(test)] mod NAME;`
  // external files, recursed like the tests/ tree.
  const srcDir = join(crateDir, 'src');
  if (existsSync(srcDir)) {
    for (const file of listRustFiles(srcDir)) {
      const rel = relative(rootDir, file);
      const raw = readFileSync(file, 'utf8');
      const { segments, externalMods } = extractTestSegments(raw);
      for (const seg of segments) {
        scannedSrcTestSegments++;
        // Segment text is newline-padded to align with the original file, so
        // the region offset is 1 (a bug here re-adds the `#[cfg(test)]`
        // prefix line count to every reported line number).
        violations.push(...scanRegion(seg.text, 1, rel));
      }
      for (const name of externalMods) {
        const modFile = modFileFor(file, name);
        if (modFile) {
          scannedSrcTestSegments++;
          scanWholeTestFile(modFile, relative(rootDir, modFile), false);
        }
      }
    }
  }
}

// --- baseline -----------------------------------------------------------------

const key = (v) => `${v.file}:${v.line}`;

// Sleep coverage allow-list (batch 6b, review Minor 1): a `sleep` baseline
// entry only covers its violation when its reason matches one of the
// sanctioned prefixes. Everything else — a missing reason, `legacy: …`,
// the `Legacy:` case variant, ad-hoc prose — is NOT coverage.
const SLEEP_COVER_RE = /^(poll-step|negative-wait|real-|D:)/;

/** Does baseline entry `b` cover violation `v`? (sleep = allow-listed reasons only) */
function baselineCovers(v, b) {
  if (!b) return false;
  if (v.type !== 'sleep') return true;
  return SLEEP_COVER_RE.test(b.reason ?? '');
}

function loadBaseline() {
  if (!existsSync(baselinePath)) return {};
  return JSON.parse(readFileSync(baselinePath, 'utf8')).violations ?? {};
}

let baseline = loadBaseline();

if (writeBaselineMode) {
  // Growth guard (batch 6b, review Minor 2): pair each violation against an
  // old entry of the same file+type group (exact line first, then the
  // leftovers in line order). Violations left unpaired are NEW additions the
  // operator must see — a brand-new file+type group, or a group whose entry
  // count grew. Pure line drift pairs up and stays silent.
  const oldByGroup = new Map();
  for (const [k, b] of Object.entries(baseline)) {
    const lineIdx = k.lastIndexOf(':');
    const group = `${k.slice(0, lineIdx)} ${b.type}`;
    const list = oldByGroup.get(group) ?? [];
    list.push({ line: Number(k.slice(lineIdx + 1)), used: false });
    oldByGroup.set(group, list);
  }
  const unmatchedByGroup = new Map();
  for (const v of violations) {
    const group = `${v.file} ${v.type}`;
    const olds = oldByGroup.get(group);
    const exact = olds?.find((o) => o.line === v.line && !o.used);
    if (exact) {
      exact.used = true;
    } else {
      const list = unmatchedByGroup.get(group) ?? [];
      list.push(v);
      unmatchedByGroup.set(group, list);
    }
  }
  const newEntries = [];
  for (const [group, vs] of unmatchedByGroup) {
    const olds = (oldByGroup.get(group) ?? []).filter((o) => !o.used);
    vs.sort((a, b) => a.line - b.line);
    olds.sort((a, b) => a.line - b.line);
    for (let i = 0; i < vs.length; i++) {
      if (i < olds.length) olds[i].used = true; // drifted line: same group, count unchanged
      else newEntries.push(vs[i]);
    }
  }

  const next = {};
  for (const v of violations) {
    // Preserve hand-curated reasons across re-anchoring (e.g. the R4
    // poll-step / negative-wait classification, the R-layer real-env audit
    // verdicts): match by file + type, not by line number.
    // Known limitation: when one file+type group holds several DIFFERENT
    // curated reasons, the first one wins for the whole group. Safe today
    // because every group is reason-homogeneous; the content-anchored key
    // planned as phase 2 will replace this matching entirely.
    const priorForFile = Object.entries(baseline).find(
      ([k, b]) => {
        if (b.type !== v.type) return false;
        const kFile = k.slice(0, k.lastIndexOf(':'));
        const vFile = v.file;
        return (
          kFile === vFile &&
          (b.reason?.startsWith('poll-step') ||
            b.reason?.startsWith('negative-wait') ||
            b.reason?.startsWith('real-io') ||
            b.reason?.startsWith('real-env'))
        );
      },
    );
    next[key(v)] = {
      type: v.type,
      reason: priorForFile
        ? priorForFile[1].reason
        : v.type === 'real-env'
          ? 'real-env: pending audit adjudication (see 2026-11-06 design §4)'
          : 'legacy: pending R2/R4 migration',
    };
  }
  baseline = next;
  mkdirSync(dirname(baselinePath), { recursive: true });
  writeFileSync(baselinePath, JSON.stringify({ violations: next }, null, 2) + '\n');
  console.log(`test-hygiene baseline written: ${Object.keys(next).length} entries -> ${relative(rootDir, baselinePath)}`);
  // Zero-tolerance: re-anchoring must not launder legacy sleep debt — warn
  // loudly that any legacy-reasoned sleep entry written here will fail the
  // next gate run (the gate, not this write, is the enforcement point).
  const legacySleeps = Object.values(next).filter(
    (e) => e.type === 'sleep' && e.reason?.startsWith('legacy'),
  ).length;
  if (legacySleeps > 0) {
    console.warn(
      `test-hygiene: ${legacySleeps} sleep entr${legacySleeps === 1 ? 'y' : 'ies'} written with a \`legacy\` reason — zero-tolerance will report ${legacySleeps === 1 ? 'it' : 'them'} as violation(s) on the next gate run`,
    );
  }
  // Growth guard (batch 6b): new file+type group entries are visible but do
  // not block the write — re-anchoring is an operator action.
  if (newEntries.length > 0) {
    const list = newEntries
      .map((v) => `${v.file}:${v.line} [${v.type}]`)
      .join('\n  ');
    console.warn(
      `test-hygiene: ${newEntries.length} NEW baseline entr${newEntries.length === 1 ? 'y' : 'ies'} (file+type group had no corresponding old entry):\n  ${list}`,
    );
    console.log(
      `test-hygiene: ${newEntries.length} new entr${newEntries.length === 1 ? 'y' : 'ies'} written — review the list above before committing the baseline`,
    );
  }
  process.exit(0);
}

