/// Request to spawn a new child agent.
#[derive(Clone)]
pub struct SpawnRequest {
    /// Profile name (e.g. `"coder"`, `"explore"`).
    pub profile_name: String,
    /// Full task prompt for the subagent.
    pub prompt: String,
    /// Short human-readable description (3-5 words).
    pub description: String,
    /// Model override; `None` inherits the parent's model.
    pub model: Option<String>,
    /// Cancel token — should be a child of the parent's cancel token so
    /// parent cancellation propagates downward.
    pub cancel: CancelToken,
    /// Whether the tool call returned immediately (background) or awaits
    /// completion — rides the `subagent.spawned` event's
    /// `runInBackground` field.
    pub run_in_background: bool,
    /// The parent tool call's id (the `Agent`/`AgentSwarm` execution
    /// context), when the spawn came from a tool call — rides the
    /// `subagent.spawned` event's `parentToolCallId` field.
    pub parent_tool_call_id: Option<String>,
    /// The swarm item's index (`AgentSwarm` batches), 0-based — rides the
    /// `subagent.spawned` event's `swarmIndex` field.
    pub swarm_index: Option<u32>,
    /// The swarm item's label (`AgentSwarm` batches) — persisted into the
    /// host's `ChildEntry` so later `resume_agent_ids` calls can relabel the
    /// resumed member's `item` attribute (TS `getSwarmItem`).
    pub swarm_item: Option<String>,
    /// Suppress the `subagent.failed` bus event when the attempt fails with
    /// a rate limit — the swarm scheduler requeues the member and publishes
    /// `subagent.suspended` instead (TS `suppressRateLimitFailureEvent`,
    /// agentRunBatch.ts:290). Default false (the Agent tool never sets it).
    pub suppress_rate_limit_failure_event: bool,
}

/// Request to resume an existing idle subagent with a new prompt.
#[derive(Clone)]
pub struct ResumeRequest {
    /// The agent ID to resume.
    pub agent_id: String,
    /// The new prompt for the resumed agent.
    pub prompt: String,
    /// Cancel token — should be a child of the parent's cancel token so
    /// parent cancellation propagates downward.
    pub cancel: CancelToken,
    /// Re-run the previously failed turn WITHOUT appending a new user
    /// message (TS `promptService.retry()`) — the rate-limit requeue path.
    /// `prompt` is ignored in this mode; the memory's last user message
    /// drives the loop.
    pub retry: bool,
    /// Suppress the `subagent.failed` bus event when the attempt fails with
    /// a rate limit (see [`SpawnRequest::suppress_rate_limit_failure_event`]).
    pub suppress_rate_limit_failure_event: bool,
}

/// Spawns and manages child agents within a session.
///
/// Implemented by the host layer (embedded server / rpc server) which
/// has access to the LLM provider, `SessionScope`, and `TurnFlow` factory.
/// The trait is injected into `BuiltinToolServices` as
/// `Option<Arc<dyn SubagentHost>>` — when `None`, the `Agent` and
/// `AgentSwarm` tools are not registered (headless/test mode).
///
/// ## Responsibilities
///
/// 1. Resolve the profile → `AgentScopeConfig` (model, system prompt, tools)
/// 2. Create a child `AgentScope` via `SessionScope::create_agent`
/// 3. Build a fresh `TurnFlow` for the child (owned, not shared)
/// 4. Run `run_one_turn` with the prompt
/// 5. Extract the final assistant text + usage as `SubagentCompletion`
/// 6. Settle the tracked child entry (running flag cleared; the entry
///    itself stays in the host's `children` table for the session's
///    lifetime so later `resume` calls work)
///
/// Lightweight info about an available subagent profile, used to build
/// dynamic tool descriptions so the LLM knows which profiles and models
/// it can select when invoking the `Agent` / `AgentSwarm` tools.
///
/// When a [`ModelCatalog`](crate::model_catalog::ModelCatalog) is wired into
/// the host, `model_capabilities` and `available_models` are populated from
/// the catalog so the tool description names concrete, valid model aliases.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct SubagentProfileInfo {
    /// Profile name (e.g. `"coder"`, `"explore"`).
    pub name: String,
    /// Model ID the profile resolves to, if known.
    pub model: Option<String>,
    /// Human-readable profile description, when known.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub description: Option<String>,
    /// Guidance on when to use this profile, when known.
    #[serde(default, skip_serializing_if = "Option::is_none", alias = "whenToUse")]
    pub when_to_use: Option<String>,
    /// The profile's tool whitelist, when it declares one (`None` = every
    /// tool). Feeds the dispatch description's `Tools:` annotation.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub tools: Option<Vec<String>>,
    /// The profile's tool denylist, when it declares one.
    #[serde(
        default,
        skip_serializing_if = "Option::is_none",
        alias = "disallowedTools"
    )]
    pub disallowed_tools: Option<Vec<String>>,
    /// Capability names of the profile's resolved model (from the model
    /// catalog), e.g. `["vision", "tool-use", "streaming"]`. Empty when no
    /// catalog is available.
    #[serde(
        default,
        skip_serializing_if = "Vec::is_empty",
        alias = "modelCapabilities"
    )]
    pub model_capabilities: Vec<String>,
    /// Model aliases valid for `model` overrides (from the model catalog).
    /// Empty when no catalog is available.
    #[serde(
        default,
        skip_serializing_if = "Vec::is_empty",
        alias = "availableModels"
    )]
    pub available_models: Vec<String>,
}

impl SubagentProfileInfo {
    /// One profile entry for the `Agent` / `AgentSwarm` dispatch
    /// descriptions: a `- {name}: {description} {when_to_use}` header
    /// followed by a `Tools:` annotation mirroring the declared tool
    /// surface (v2 `buildProfileDescriptions` semantics, minus the
    /// externally-restricted intersection which the scope layer controls):
    /// an explicit whitelist renders its comma-joined names, an empty one
    /// renders `none`, a denylist renders `all except …`, and no
    /// declaration renders `all`.
    pub fn dispatch_description_line(&self) -> String {
        let details: Vec<&str> = self
            .description
            .as_deref()
            .into_iter()
            .chain(self.when_to_use.as_deref())
            .filter(|d| !d.is_empty())
            .collect();
        let header = if details.is_empty() {
            format!("- {}", self.name)
        } else {
            format!("- {}: {}", self.name, details.join(" "))
        };
        let tools_line = match (&self.tools, &self.disallowed_tools) {
            (Some(whitelist), _) if whitelist.is_empty() => "  Tools: none".to_string(),
            (Some(whitelist), _) => format!("  Tools: {}", whitelist.join(", ")),
            (None, Some(denied)) if !denied.is_empty() => {
                format!("  Tools: all except {}", denied.join(", "))
            }
            (None, _) => "  Tools: all".to_string(),
        };
        format!("{header}\n{tools_line}")
    }
}

pub trait SubagentHost: Send + Sync {
    /// Spawn a new child agent with the given profile and prompt.
    ///
    /// Returns a handle whose `completion` future resolves when the child
    /// finishes its turn. The host owns all lifecycle management — the
    /// caller only awaits the completion.
    fn spawn(&self, request: SpawnRequest) -> EngineResult<SubagentHandle>;

    /// Resume an existing idle subagent with a new prompt.
    ///
    /// Returns `Err` if the agent_id is not found, already running, or
    /// does not belong to this session.
    fn resume(&self, request: ResumeRequest) -> EngineResult<SubagentHandle>;

    /// Forget a child outright — used when a dispatch was rejected AFTER
    /// the spawn side effects (the residual capacity race in the Agent
    /// tool): the completion future will never be polled, so the children
    /// entry must not linger as resumable state. The default is a no-op
    /// (hosts without child tracking).
    fn forget_child(&self, _agent_id: &str) {}

    /// Whether a run of this child is currently in flight (the children
    /// map's `running` flag, G13). The notification driver consults it for
    /// a subagent notification addressee: a child's turn is driven by this
    /// host's completion future, invisible to the driver's own flow map —
    /// without this probe the driver could run a notification turn
    /// concurrently with the child's in-flight run (B4 review S3). The
    /// default is `false` (hosts without child tracking).
    fn is_child_running(&self, _agent_id: &str) -> bool {
        false
    }

    /// Atomically claim a notification turn on this host's child (B4
    /// review round 2, F1): check-and-set the per-child `running` flag
    /// under the children-map lock, returning a guard that releases the
    /// claim when dropped. `None` when the child is unknown to this host
    /// or currently running — the caller must treat the child as busy
    /// (park, retry a later tick). The claim closes the probe's TOCTOU:
    /// a point-in-time [`Self::is_child_running`] probe races a host
    /// `spawn`/`resume` started right after it, while the claim and those
    /// paths take-and-test the same flag under the same map lock.
    /// The default (hosts without child tracking) succeeds with a no-op
    /// guard: there is nothing to exclude against.
    fn claim_child_notification_turn(&self, _agent_id: &str) -> Option<NotificationRunGuard> {
        Some(NotificationRunGuard::noop())
    }

    /// Announce a member was parked for a later retry (the
    /// `subagent.suspended` wire event) with the structured cause
    /// (ADR-011). Default no-op (hosts without a bus).
    fn notify_suspended(&self, _agent_id: &str, _cause: &SuspendCause) {}

    /// The persisted swarm item label of a child spawned by this host
    /// (TS `getSwarmItem` — ownership implied by the per-parent host).
    /// `AgentSwarm` consults it when relabeling a resumed member's result
    /// row with the item it was originally spawned with. The default is
    /// `None` (hosts without child tracking).
    fn swarm_item_of(&self, _agent_id: &str) -> Option<String> {
        None
    }

    /// Return the profiles available for subagent dispatch.
    ///
    /// Used by `AgentTool` / `AgentSwarmTool` to build dynamic descriptions
    /// that list available profiles and their models. The default
    /// implementation returns an empty vec (headless/test mode).
    fn available_profiles(&self) -> Vec<SubagentProfileInfo> {
        Vec::new()
    }

    /// Return the curated model entries for the LLM perception surface.
    ///
    /// A model is curated when it carries a non-empty `description` — the
    /// sole visibility gate on what the LLM sees (D-M10.1). Used by
    /// `AgentTool` / `AgentSwarmTool` to list pickable aliases and by the
    /// spawn validation error as a self-correction hint. The default
    /// implementation returns no curated models (headless/test mode).
    fn curated_models(&self) -> Vec<crate::model_catalog::ModelCatalogEntry> {
        Vec::new()
    }
}

