//! Subagent task system — background delegation to child agents.
//!
//! This module ports the TypeScript subagent system, providing the types and
//! lifecycle for spawning a child agent as a tracked background task.
//!
//! ## Architecture
//!
//! ```text
//! SubagentHandle  (agent_id, profile, model, completion future)
//!       │
//!       ▼
//! SubagentTask   (handle + description + cancel token)
//!       │
//!       ▼  start(sink)
//! TaskSink       (append_output, settle, signal, record_usage)
//! ```
//!
//! A [`SubagentHandle`] wraps a `Pin<Box<dyn Future<Output = SubagentCompletion>>>`
//! — the unit of work delegated to the child agent. [`SubagentTask`] drives the
//! handle to completion (or cancellation) and reports progress through a
//! [`TaskSink`], bridging subagent execution into the session's
//! [`TaskManager`](crate::task::TaskManager) tracking.

use std::future::Future;
use std::panic::AssertUnwindSafe;
use std::pin::Pin;
use std::sync::Arc;

use futures::FutureExt;
use serde::{Deserialize, Serialize};

use crate::cancel::CancelToken;
use crate::error::EngineResult;
use crate::loop_engine::TurnStopReason;
use crate::task::TaskStatus;

/// Token usage accounting for a subagent completion.
///
/// Mirrors [`crate::llm::LlmUsage`] but is a separate type so the subagent
/// module is self-contained and does not tightly couple to the LLM layer.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct TokenUsage {
    /// Tokens consumed in the prompt (input).
    pub input_tokens: u64,
    /// Tokens generated by the model (output).
    pub output_tokens: u64,
    /// Prompt tokens served from cache.
    #[serde(default)]
    pub cache_read_tokens: u64,
    /// Prompt tokens written to cache.
    #[serde(default)]
    pub cache_creation_tokens: u64,
}

/// The result of a subagent's execution.
///
/// Produced when the child agent's completion future resolves. The `result`
/// string is the final output the subagent produced; `usage` carries token
/// accounting if the subagent performed LLM calls; `stop_reason` carries the
/// child turn's terminal reason (ADR-010) so the task face can distinguish
/// a genuinely completed turn from one that ended filtered / paused /
/// blocked / unknown.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct SubagentCompletion {
    /// The final output text from the subagent.
    pub result: String,
    /// Token usage if the subagent performed LLM calls.
    pub usage: Option<TokenUsage>,
    /// The child turn's terminal stop reason.
    pub stop_reason: TurnStopReason,
}

impl SubagentCompletion {
    /// Create a completion with just a result string and no usage — an
    /// `EndTurn` (a naturally finished turn) is the semantic default.
    pub fn from_text(result: impl Into<String>) -> Self {
        Self {
            result: result.into(),
            usage: None,
            stop_reason: TurnStopReason::EndTurn,
        }
    }

    /// Create a completion with a result and token usage — an `EndTurn` (a
    /// naturally finished turn) is the semantic default.
    pub fn with_usage(result: impl Into<String>, usage: TokenUsage) -> Self {
        Self {
            result: result.into(),
            usage: Some(usage),
            stop_reason: TurnStopReason::EndTurn,
        }
    }
}

/// Error produced when a subagent's turn fails.
///
/// Unlike a panic (caught by `catch_unwind`), this represents a structured
/// failure from the agent loop — LLM error, context overflow, timeout, etc.
#[derive(Debug, Clone)]
pub enum SubagentError {
    /// The child agent's turn returned an `EngineError`.
    TurnFailed(String),
    /// The child agent was cancelled before completing.
    Cancelled,
    /// A transient provider rate limit (HTTP 429 / rate-limit wording, NOT a
    /// billing-anchored quota 429 — those stay [`SubagentError::TurnFailed`],
    /// mirroring the TS `isProviderRateLimitError` which excludes quota
    /// exhaustion). The swarm scheduler requeues the member on the same agent
    /// identity.
    RateLimited(String),
}

/// The structured reason a member is suspended (ADR-011): the wire
/// `event.subagent.suspended` payload's `reason` is a snake_case JSON
/// object `{ kind: "approval" | "question" | "rate_limit", request_id?,
/// tool_call_id? }` — machine-readable for consumers that render the
/// member's awaiting-user state. The pre-structuring free-form string stays
/// receivable through the [`Self::Legacy`] form — the compat window where
/// old consumers must not crash on the new shape and new consumers must not
/// crash on old strings (serde maps a string reason to `Legacy`, and the
/// projection passes it through unchanged).
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum SuspendCause {
    /// The member awaits a user's approval decision (the approval gate
    /// holds a pending request). Carries the minted gate `request_id` and
    /// the id of the tool call whose execution is gated.
    Approval {
        request_id: String,
        tool_call_id: Option<String>,
    },
    /// The member awaits a user's answer to a question.
    Question {
        request_id: String,
        tool_call_id: Option<String>,
    },
    /// The member is backed off for a provider rate limit (the swarm
    /// scheduler's requeue parking).
    RateLimit,
    /// A pre-ADR-011 free-form reason — replayed from older streams or
    /// journals, or an unknown shape preserved verbatim (never a crash).
    Legacy(String),
}

/// The wire shape of a structured [`SuspendCause`] — `{ kind, request_id?,
/// tool_call_id? }` with snake_case keys. `tool_call_id` omits (never a
/// null placeholder) when the cause carries none.
#[derive(Debug, Clone, serde::Serialize, serde::Deserialize)]
#[serde(tag = "kind", rename_all = "snake_case")]
enum SuspendCauseWire {
    Approval {
        request_id: String,
        #[serde(skip_serializing_if = "Option::is_none")]
        tool_call_id: Option<String>,
    },
    Question {
        request_id: String,
        #[serde(skip_serializing_if = "Option::is_none")]
        tool_call_id: Option<String>,
    },
    RateLimit,
}

impl From<&SuspendCause> for SuspendCauseWire {
    fn from(cause: &SuspendCause) -> Self {
        match cause {
            SuspendCause::Approval {
                request_id,
                tool_call_id,
            } => SuspendCauseWire::Approval {
                request_id: request_id.clone(),
                tool_call_id: tool_call_id.clone(),
            },
            SuspendCause::Question {
                request_id,
                tool_call_id,
            } => SuspendCauseWire::Question {
                request_id: request_id.clone(),
                tool_call_id: tool_call_id.clone(),
            },
            SuspendCause::RateLimit => SuspendCauseWire::RateLimit,
            SuspendCause::Legacy(_) => {
                unreachable!(
                    "a Legacy cause serializes as a plain string, never through the wire shape"
                )
            }
        }
    }
}

impl From<SuspendCauseWire> for SuspendCause {
    fn from(wire: SuspendCauseWire) -> Self {
        match wire {
            SuspendCauseWire::Approval {
                request_id,
                tool_call_id,
            } => SuspendCause::Approval {
                request_id,
                tool_call_id,
            },
            SuspendCauseWire::Question {
                request_id,
                tool_call_id,
            } => SuspendCause::Question {
                request_id,
                tool_call_id,
            },
            SuspendCauseWire::RateLimit => SuspendCause::RateLimit,
        }
    }
}

impl serde::Serialize for SuspendCause {
    fn serialize<S>(&self, serializer: S) -> Result<S::Ok, S::Error>
    where
        S: serde::Serializer,
    {
        match self {
            // The legacy string stays a plain JSON string — consumers
            // discriminate the two shapes with `typeof` (ADR-011 compat).
            SuspendCause::Legacy(text) => serializer.serialize_str(text),
            structured => SuspendCauseWire::from(structured).serialize(serializer),
        }
    }
}

impl<'de> serde::Deserialize<'de> for SuspendCause {
    fn deserialize<D>(deserializer: D) -> Result<Self, D::Error>
    where
        D: serde::Deserializer<'de>,
    {
        let value = serde_json::Value::deserialize(deserializer)?;
        match value {
            serde_json::Value::String(text) => Ok(SuspendCause::Legacy(text)),
            other => match serde_json::from_value::<SuspendCauseWire>(other.clone()) {
                Ok(wire) => Ok(wire.into()),
                // An unknown shape never crashes a consumer — the reason is
                // preserved verbatim as a legacy string.
                Err(_) => Ok(SuspendCause::Legacy(other.to_string())),
            },
        }
    }
}

impl std::fmt::Display for SuspendCause {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        match self {
            SuspendCause::Approval { request_id, .. } => {
                write!(f, "Awaiting user approval (request {request_id})")
            }
            SuspendCause::Question { request_id, .. } => {
                write!(f, "Awaiting user answer (request {request_id})")
            }
            // The migrated display string of the old
            // `RATE_LIMIT_SUSPENDED_REASON` const (ADR-011).
            SuspendCause::RateLimit => {
                f.write_str(crate::subagent::swarm_batch::RATE_LIMIT_SUSPENDED_REASON)
            }
            SuspendCause::Legacy(text) => f.write_str(text),
        }
    }
}

/// One edge of a member's suspension lifecycle (ADR-011).
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum SuspensionNotice {
    /// The member parked; `cause` explains why (e.g. an approval ask
    /// registered with the gate).
    Suspended(SuspendCause),
    /// The suspension ended and the member's turn continues.
    Resumed,
}

/// The suspension-boundary callback a child turn flow reports into
/// (ADR-011): wired by the subagent host at each spawn/resume face — the
/// same injection pattern as the interaction kernel
/// ([`TurnFlow::set_interaction_kernel`](crate::turn_flow::TurnFlow::set_interaction_kernel))
/// — so the host stays the single publisher of the
/// `subagent.suspended` / `subagent.started` pairing.
pub type SuspensionNotify = Arc<dyn Fn(SuspensionNotice) + Send + Sync>;

/// A boxed, pinned future that produces a subagent completion or error.
///
/// The `Result` return type lets the host propagate structured failures
/// (LLM errors, context overflow, provider safety blocks) instead of
/// encoding them as panic messages or swallowing them into the result text.
pub type CompletionFuture =
    Pin<Box<dyn Future<Output = Result<SubagentCompletion, SubagentError>> + Send>>;

/// Handle to a running subagent — wraps the completion future and metadata.
///
/// Created by the host when it spawns a child agent. The `completion` future
/// resolves when the child agent finishes its turn. The host can poll the
/// future directly or wrap it in a [`SubagentTask`] for managed lifecycle.
pub struct SubagentHandle {
    /// Unique identifier for the subagent instance.
    pub agent_id: String,
    /// Profile name (e.g. `"coder"`, `"explore"`).
    pub profile_name: String,
    /// Model override, if any.
    pub model: Option<String>,
    /// The future that resolves to the subagent's completion.
    pub completion: CompletionFuture,
    /// The child's engine activity source — its TurnFlow's
    /// [`ActivityTracker`](crate::turn_flow::ActivityTracker), whose
    /// observation points (LLM steps, tool calls) fire while the completion
    /// future is in flight. Set by hosts that run real engine turns
    /// ([`SessionSubagentHost`](host::SessionSubagentHost)); `None` for
    /// synthetic / test handles. The tool layer polls it to forward real
    /// activity into the tracked task's liveness window (activity-as-
    /// liveness), so a live subagent never reads as stale.
    pub activity: Option<std::sync::Arc<crate::turn_flow::ActivityTracker>>,
    /// The child's per-turn wait registry — the child's OWN await points
    /// (its TaskOutput wait, its gate waits) register here. A PARENT
    /// waiting on this child probes its own registry; when the child's
    /// activity clock is frozen (the child is itself waiting on something
    /// else — a transitive wait chain), the parent's WaitingSubagent
    /// verdict falls back to probing the CHILD's registry: a child
    /// healthily waiting on an advancing task is Advancing up the chain
    /// (ADR-006 wait-chain propagation, the fork/converted-task e2e
    /// shape). `None` for synthetic / test handles.
    pub wait_registry: Option<std::sync::Arc<crate::turn_flow::WaitRegistry>>,
    /// The member's suspension-boundary feed (ADR-011): the host forwards
    /// every approval-gate `Suspended` / `Resumed` notice of this member's
    /// turn into the paired sender, and the swarm scheduler reads them
    /// (through this receiver) to stop the member's attempt clock (ADR-011
    /// c) and free its concurrency slot (ADR-011 d) while it awaits a user
    /// decision. `None` for synthetic / test handles (no parking signals).
    pub suspension_rx: Option<tokio::sync::mpsc::UnboundedReceiver<SuspensionNotice>>,
}

impl SubagentHandle {
    /// Create a new handle from its parts.
    pub fn new(
        agent_id: String,
        profile_name: String,
        model: Option<String>,
        completion: CompletionFuture,
    ) -> Self {
        Self {
            agent_id,
            profile_name,
            model,
            completion,
            activity: None,
            wait_registry: None,
            suspension_rx: None,
        }
    }

    /// Attach the member's suspension-boundary feed (see
    /// [`Self::suspension_rx`]). Builder style: consumes and returns the
    /// handle.
    pub fn with_suspension_rx(
        mut self,
        suspension_rx: tokio::sync::mpsc::UnboundedReceiver<SuspensionNotice>,
    ) -> Self {
        self.suspension_rx = Some(suspension_rx);
        self
    }

    /// Attach the child's engine activity source (see
    /// [`Self::activity`]). Builder style: consumes and returns the handle.
    pub fn with_activity(
        mut self,
        activity: std::sync::Arc<crate::turn_flow::ActivityTracker>,
    ) -> Self {
        self.activity = Some(activity);
        self
    }

    /// Attach the child's per-turn wait registry (see
    /// [`Self::wait_registry`]). Builder style.
    pub fn with_wait_registry(
        mut self,
        wait_registry: std::sync::Arc<crate::turn_flow::WaitRegistry>,
    ) -> Self {
        self.wait_registry = Some(wait_registry);
        self
    }

    /// Create a handle that immediately resolves with the given result text.
    ///
    /// Convenience for tests and synchronous subagent results.
    pub fn from_result(
        agent_id: String,
        profile_name: String,
        model: Option<String>,
        result: String,
    ) -> Self {
        let completion = Box::pin(async move { Ok(SubagentCompletion::from_text(result)) });
        Self::new(agent_id, profile_name, model, completion)
    }

    /// Create a handle that immediately resolves with an error.
    ///
    /// Convenience for tests.
    pub fn from_error(
        agent_id: String,
        profile_name: String,
        model: Option<String>,
        error: String,
    ) -> Self {
        let completion = Box::pin(async move { Err(SubagentError::TurnFailed(error)) });
        Self::new(agent_id, profile_name, model, completion)
    }

    /// Create a handle that never resolves (useful for testing cancellation).
    pub fn never_completing(agent_id: String, profile_name: String, model: Option<String>) -> Self {
        let completion = Box::pin(std::future::pending::<
            Result<SubagentCompletion, SubagentError>,
        >());
        Self::new(agent_id, profile_name, model, completion)
    }
}

/// Wire-protocol info about a subagent task.
///
/// Serialised and sent to the host so it can render the subagent in the UI
/// task list. The `kind` field is always `"agent"` to distinguish subagent
/// tasks from shell-command tasks.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct SubagentTaskInfo {
    /// Always `"agent"`.
    pub kind: String,
    /// The subagent's agent id, if assigned.
    pub agent_id: Option<String>,
    /// The subagent type (profile name), if any.
    pub subagent_type: Option<String>,
    /// Model override, if any.
    pub model: Option<String>,
    /// Human-readable description.
    pub description: String,
    /// Current status string (e.g. `"running"`, `"completed"`, `"stopped"`).
    pub status: String,
}

/// Sink for receiving task output and status updates.
///
/// Implementations bridge into the session's
/// [`TaskManager`](crate::task::TaskManager). The trait is kept minimal so
/// that test doubles can be constructed trivially.
pub trait TaskSink: Send {
    /// Append output data to the task's accumulated output.
    fn append_output(&mut self, data: &str);
    /// Settle the task with a final status and optional stop reason.
    fn settle(&mut self, status: TaskStatus, stop_reason: Option<String>);
    /// Get the cancel token for this task.
    fn signal(&self) -> &CancelToken;
    /// Record token usage reported by the subagent's completion.
    ///
    /// Defaults to a no-op so existing implementors are unaffected; sinks
    /// that track token accounting (e.g. a session budget) override it.
    fn record_usage(&mut self, _usage: &TokenUsage) {}
}

/// A subagent executing as a tracked background task.
///
/// Wraps a [`SubagentHandle`] and drives it to completion (or cancellation)
/// via [`SubagentTask::start`], reporting progress through a [`TaskSink`].
///
/// ## Lifecycle
///
/// 1. The host creates a [`SubagentHandle`] when spawning a child agent.
/// 2. The handle is wrapped in a `SubagentTask` with a description and
///    [`CancelToken`].
/// 3. [`SubagentTask::start`] is awaited with a [`TaskSink`].
/// 4. The task races the completion future against cancellation from either
///    the sink's signal or the task's own [`CancelToken`]:
///    - **Completion wins** → result is appended to the sink, token usage
///      recorded, and the task settles by the completion's terminal stop
///      reason (ADR-010): `EndTurn` → [`TaskStatus::Completed`], every
///      other reason → [`TaskStatus::Failed`] naming the reason.
///    - **Completion panics** → caught, and the task settles as
///      [`TaskStatus::Failed`] with the panic message.
///    - **Cancellation wins** → task settles as [`TaskStatus::Stopped`].
pub struct SubagentTask {
    /// The subagent handle (owns the completion future).
    pub handle: SubagentHandle,
    /// Human-readable description of the work.
    pub description: String,
    /// Cancel token for this task.
    pub cancel: CancelToken,
}

impl SubagentTask {
    /// Task kind identifier — always `"agent"`.
    pub fn kind() -> &'static str {
        "agent"
    }

    /// ID prefix for task registration — always `"agent"`.
    pub fn id_prefix() -> &'static str {
        "agent"
    }

    /// The subagent's agent id.
    pub fn agent_id(&self) -> &str {
        &self.handle.agent_id
    }

    /// The subagent type (profile name).
    pub fn subagent_type(&self) -> &str {
        &self.handle.profile_name
    }

    /// The model override, if any.
    pub fn model(&self) -> Option<&str> {
        self.handle.model.as_deref()
    }

    /// Create a new subagent task.
    pub fn new(handle: SubagentHandle, description: String, cancel: CancelToken) -> Self {
        Self {
            handle,
            description,
            cancel,
        }
    }

    /// Convert to a wire-protocol info struct with the given status string.
    pub fn to_info(&self, status: &str) -> SubagentTaskInfo {
        SubagentTaskInfo {
            kind: Self::kind().to_string(),
            agent_id: Some(self.handle.agent_id.clone()),
            subagent_type: Some(self.handle.profile_name.clone()),
            model: self.handle.model.clone(),
            description: self.description.clone(),
            status: status.to_string(),
        }
    }

    /// Start the subagent task, driving it to completion or cancellation.
    ///
    /// - If the completion future resolves first: appends the result to the
    ///   sink, records any token usage, and settles the task by the
    ///   completion's terminal stop reason (ADR-010): `EndTurn` → completed
    ///   with exit code 0; `Filtered` / `Paused` / `BlockedByHook` /
    ///   `Unknown` → failed with the reason named. `MaxTokens` / `Aborted`
    ///   are unreachable from the host (it converts those turns into
    ///   [`SubagentError`]s before a completion is ever built) and are
    ///   mapped fail-safe.
    /// - If the completion future panics: the panic is caught (see
    ///   [`FutureExt::catch_unwind`]) and the task settles as
    ///   [`TaskStatus::Failed`] with the panic message and stop reason
    ///   `"panic"`.
    /// - If either the sink's cancel signal or the task's own
    ///   [`CancelToken`] fires first: settles as [`TaskStatus::Stopped`]
    ///   with the stop reason `"cancelled"`.
    ///
    /// When the result is empty, a placeholder message is appended so the
    /// task output is never silently blank.
    pub async fn start(&mut self, sink: &mut dyn TaskSink) {
        let cancel = sink.signal().clone();

        tokio::select! {
            completion = AssertUnwindSafe(&mut self.handle.completion).catch_unwind() => {
                match completion {
                    Ok(Ok(completion)) => {
                        if completion.result.is_empty() {
                            sink.append_output("(subagent produced no output)");
                        } else {
                            sink.append_output(&completion.result);
                        }
                        if let Some(usage) = &completion.usage {
                            sink.record_usage(usage);
                        }
                        // ADR-010 (audit P2-2): the settlement truthfully
                        // reflects how the child turn ended — a turn that
                        // ended filtered / paused / blocked / unknown is a
                        // failure, not a success. MaxTokens/Aborted never
                        // reach this face (the host converts them to Err
                        // before a completion is built); they map fail-safe.
                        let (status, reason) = match completion.stop_reason {
                            TurnStopReason::EndTurn => {
                                (TaskStatus::Completed { exit_code: 0 }, None)
                            }
                            TurnStopReason::Filtered => (
                                TaskStatus::Failed("turn ended with filtered output".to_string()),
                                Some("filtered".to_string()),
                            ),
                            TurnStopReason::Paused => (
                                TaskStatus::Failed("turn ended paused".to_string()),
                                Some("paused".to_string()),
                            ),
                            TurnStopReason::BlockedByHook => (
                                TaskStatus::Failed("turn blocked by hook".to_string()),
                                Some("blocked_by_hook".to_string()),
                            ),
                            TurnStopReason::Stalled => (
                                TaskStatus::Failed("turn stalled (no progress)".to_string()),
                                Some("stalled".to_string()),
                            ),
                            TurnStopReason::Unknown => (
                                TaskStatus::Failed("turn ended for an unknown reason".to_string()),
                                Some("unknown".to_string()),
                            ),
                            TurnStopReason::MaxTokens => (
                                TaskStatus::Failed("turn ended with max tokens".to_string()),
                                Some("max_tokens".to_string()),
                            ),
                            TurnStopReason::Aborted => (
                                TaskStatus::Failed("turn aborted".to_string()),
                                Some("aborted".to_string()),
                            ),
                        };
                        sink.settle(status, reason);
                    }
                    Ok(Err(SubagentError::TurnFailed(msg))) => {
                        sink.append_output(&format!("(subagent failed: {msg})"));
                        sink.settle(
                            TaskStatus::Failed(format!(
                                "subagent '{}' failed: {}",
                                self.handle.agent_id, msg
                            )),
                            Some("turn_failed".to_string()),
                        );
                    }
                    Ok(Err(SubagentError::RateLimited(msg))) => {
                        // Same terminal shape as TurnFailed, distinguished by
                        // the stop reason — the swarm scheduler's requeue path
                        // observes the requeue-capable error BEFORE this sink
                        // face ever runs (the Agent tool's detached face is the
                        // only consumer that lands here today).
                        sink.append_output(&format!("(subagent failed: {msg})"));
                        sink.settle(
                            TaskStatus::Failed(format!(
                                "subagent '{}' failed: {}",
                                self.handle.agent_id, msg
                            )),
                            Some("rate_limited".to_string()),
                        );
                    }
                    Ok(Err(SubagentError::Cancelled)) => {
                        sink.append_output("(subagent cancelled)");
                        sink.settle(
                            TaskStatus::Stopped,
                            Some("cancelled".to_string()),
                        );
                    }
                    Err(panic_payload) => {
                        let message = panic_payload
                            .downcast_ref::<&'static str>()
                            .copied()
                            .or_else(|| {
                                panic_payload.downcast_ref::<String>().map(String::as_str)
                            })
                            .unwrap_or("(no panic message)");
                        let message = match crate::panic_capture::take_last_panic_location() {
                            Some(location) => format!("{message} (panic at {location})"),
                            None => message.to_string(),
                        };
                        sink.append_output(&format!("(subagent panicked: {message})"));
                        sink.settle(
                            TaskStatus::Failed(format!(
                                "subagent '{}' panicked: {}",
                                self.handle.agent_id, message
                            )),
                            Some("panic".to_string()),
                        );
                    }
                }
            }
            _ = cancel.cancelled() => {
                sink.settle(
                    TaskStatus::Stopped,
                    Some("cancelled".to_string()),
                );
            }
            _ = self.cancel.cancelled() => {
                sink.settle(
                    TaskStatus::Stopped,
                    Some("cancelled".to_string()),
                );
            }
        }
    }
}

